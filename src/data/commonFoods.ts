// Wbudowana baza produktów i składników (na 100 g / 100 ml / sztukę).
// Współdzielona przez licznik kalorii i kreator posiłku.

export interface FoodItem {
  name: string;
  calories: number;
  protein: number;
  carbs: number;
  fat: number;
  unit: string;
  description?: string;
  portionG?: number;
  gramsPerPiece?: number; // waga 1 sztuki — pozwala przełączyć „szt" na wagę
  keywords?: string;      // synonimy, np. „filet" dla piersi z indyka
}

// Wyszukiwanie bez rozróżniania polskich znaków — „maslanka" znajdzie „Maślanka".
export function normalizeText(s: string): string {
  return s.toLowerCase()
    .replace(/ą/g, 'a').replace(/ę/g, 'e').replace(/ó/g, 'o').replace(/ś/g, 's')
    .replace(/ż/g, 'z').replace(/ź/g, 'z').replace(/ć/g, 'c').replace(/ń/g, 'n').replace(/ł/g, 'l');
}

/**
 * Dopasowanie produktu do wpisanego tekstu. Szuka KAŻDEGO słowa osobno
 * (w dowolnej kolejności), więc „pierś kurczaka" czy „kurczak pierś" znajdzie
 * „Pierś z kurczaka". Uwzględnia też synonimy z pola `keywords`.
 */
export function matchesQuery(item: { name: string; keywords?: string }, query: string): boolean {
  const q = normalizeText(query).trim();
  if (!q) return true;
  const hay = normalizeText(`${item.name} ${item.keywords ?? ''}`);
  return q.split(/\s+/).every((w) => hay.includes(w));
}

